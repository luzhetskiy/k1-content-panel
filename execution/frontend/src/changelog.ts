/**
 * Список доработок панели — то, что видит пользователь в разделе «Доработки».
 *
 * Записи лежат в коде, а не в базе, намеренно: доработка попадает в панель тем
 * же деплоем, что и сама доработка, и не может разойтись с тем, что реально
 * выкачено. Новая запись добавляется первой в массив — порядок в списке равен
 * порядку на экране, сортировки по дате нет.
 *
 * kind:
 *   feature — новая возможность;
 *   fix     — исправление в работе панели или в том, как собираются страницы;
 *   batch   — разовые работы по уже собранным партиям (пересборка компаний,
 *             правка опубликованных страниц) — то, что меняется на сайтах без
 *             участия пользователя.
 */

