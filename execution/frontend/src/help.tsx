export default function HelpButton({ section }: { section: HelpSection }) {
  const [open, setOpen] = useState(false)
  const help = HELP[section]
  return (
    <>
      <Button icon={<QuestionCircleOutlined />} onClick={() => setOpen(true)}>Справка</Button>
      <Modal open={open} title={help.title} footer={null} width={640}
             onCancel={() => setOpen(false)}>
        <ol style={{ paddingLeft: 20, margin: 0 }}>
          {help.steps.map((step, i) => (
            <li key={i} style={{ marginBottom: 8 }}>{step}</li>
          ))}
        </ol>
        {help.notes && (
          <>
            <Typography.Title level={5} style={{ marginTop: 16 }}>Полезно знать</Typography.Title>
            {help.notes.map((note, i) => (
              <Typography.Paragraph key={i} style={{ marginBottom: 8 }}>{note}</Typography.Paragraph>
            ))}
          </>
        )}
      </Modal>
    </>
  )
}
